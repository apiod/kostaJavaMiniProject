-- =========================================
-- Rental 상태 규칙 검증
-- 아래 조회 결과가 0건이면 상태 조합이 정상
-- =========================================

-- Enum에 없는 상태값 확인
SELECT RentalNum, BorrowerID, Status, PostNum
FROM Rental
WHERE Status NOT IN (100, 101, 102, 110, 200, 201, 210, 211);

-- 한 Post에 진행 중인 Rental이 2건 이상이거나,
-- 진행 건이 있는데 100(대기 중 신청)이 남아 있는 경우 확인
SELECT
    PostNum,
    SUM(CASE WHEN Status IN (101, 110, 200, 201, 210, 211) THEN 1 ELSE 0 END) AS ProgressedCount,
    SUM(CASE WHEN Status = 100 THEN 1 ELSE 0 END) AS RequestedCount,
    SUM(CASE WHEN Status = 102 THEN 1 ELSE 0 END) AS RejectedCount
FROM Rental
GROUP BY PostNum
HAVING ProgressedCount > 1
    OR (ProgressedCount = 1 AND RequestedCount > 0);

-- Post별 현재 상태 확인
SELECT
    PostNum,
    GROUP_CONCAT(CONCAT(BorrowerID, ':', Status) ORDER BY RentalNum SEPARATOR ', ') AS RentalStates
FROM Rental
GROUP BY PostNum
ORDER BY PostNum;

-- Rental 상태와 Item 대여 가능 상태가 맞지 않는 물품 확인
-- Rental이 없거나 100/102만 있으면 Item.Status = 1
-- 101/110/200/201/210/211 중 하나라도 있으면 Item.Status = 0
-- 아래 조회 결과가 0건이면 정상
SELECT
    i.ItemNum,
    i.Status AS ItemStatus,
    GROUP_CONCAT(r.Status ORDER BY r.RentalNum SEPARATOR ', ') AS RentalStatuses
FROM Item i
LEFT JOIN Post p ON i.ItemNum = p.ItemNum
LEFT JOIN Rental r ON p.PostNum = r.PostNum
GROUP BY i.ItemNum, i.Status
HAVING i.Status <> CASE
    WHEN COUNT(r.RentalNum) = 0
      OR SUM(r.Status IN (101, 110, 200, 201, 210, 211)) = 0 THEN 1
    ELSE 0
END;
