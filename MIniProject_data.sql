SELECT * FROM Rental;

SELECT r.RentalNum, r.BorrowerID, i.LenderID, i.ItemName, r.Status, r.Postnum
FROM Rental r
JOIN Post p ON r.Postnum = p.Postnum
JOIN Item i ON p.ItemNum = i.ItemNum
WHERE r.BorrowerID = i.LenderID;
